#!/bin/sh
# Regenerates src/vulkan/geometry_frag.inc: sfiii-native's native/geometry.hlsl compiled to SPIR-V with
# DXC 1.9.2609 (the version sfiii-native's tools/windows.cmake pins), the same flags as its Vulkan build.
# Usage: DXC=/path/to/dxc tools/ps5/gen-geometry-spv.sh
set -e
cd "$(dirname "$0")/../.."
src=external/sfiii-native/native/geometry.hlsl
tmp=$(mktemp)
"${DXC:-dxc}" -T ps_6_0 -E main -O3 -spirv -fspv-target-env=vulkan1.0 "$src" -Fo "$tmp"
{
  echo "// Generated by tools/ps5/gen-geometry-spv.sh from $src (sfiii-native $(git -C external/sfiii-native rev-parse --short HEAD), MIT)."
  echo "// $("${DXC:-dxc}" --version 2>&1 | head -1)"
  echo "#pragma once"
  echo "#include <cstdint>"
  echo "const uint32_t kGeometryFrag[] = {"
  od -An -v -tx4 -w32 "$tmp" | sed 's/ \([0-9a-f]\{8\}\)/0x\1,/g; s/^/    /'
  echo "};"
} > src/vulkan/geometry_frag.inc
rm -f "$tmp"
