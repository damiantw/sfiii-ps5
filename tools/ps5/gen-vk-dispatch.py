"""Generate ps5/platform/vk_dispatch.cpp (MIT): the Vulkan entry points an application links
against, forwarding to RADV's ICD interface (vk_icdGetInstanceProcAddr), since the console has no
Vulkan loader.

    python3 tools/ps5/gen-vk-dispatch.py VULKAN_CORE_H > ps5/platform/vk_dispatch.cpp

Every non-extension-guarded command in vulkan_core.h is generated (core plus KHR surface, swapchain
and display). Global commands resolve with a null instance; the rest with the instance the
application created last.
"""
import re
import sys

src = open(sys.argv[1]).read()
src = re.sub(r'#ifndef VK_NO_PROTOTYPES', '', src)
protos = re.findall(r'VKAPI_ATTR\s+([\w\s\*]+?)\s+VKAPI_CALL\s+(vk\w+)\s*\(([^;]*?)\);', src, re.S)
GLOBAL = {'vkCreateInstance', 'vkEnumerateInstanceExtensionProperties', 'vkEnumerateInstanceLayerProperties',
          'vkEnumerateInstanceVersion'}
out = ['// SPDX-License-Identifier: MIT',
       '// Generated by tools/ps5/gen-vk-dispatch.py from vulkan_core.h. Do not edit; regenerate.',
       '#include <vulkan/vulkan_core.h>', '',
       'extern "C" VKAPI_ATTR PFN_vkVoidFunction VKAPI_CALL vk_icdGetInstanceProcAddr(VkInstance, const char*);',
       'namespace { VkInstance g_instance = VK_NULL_HANDLE; }', '']
seen = set()
for ret, name, params in protos:
    if name in seen or name in ('vkGetInstanceProcAddr',):
        continue
    seen.add(name)
    params = ' '.join(params.split())
    names = [re.findall(r'(\w+)(?:\s*\[[^\]]*\])?\s*$', p.strip())[0] for p in params.split(',') if p.strip() and p.strip() != 'void']
    inst = 'VK_NULL_HANDLE' if name in GLOBAL else 'g_instance'
    call = '%s(%s)' % ('f', ', '.join(names))
    body = 'static auto f = (PFN_%s)vk_icdGetInstanceProcAddr(%s, "%s"); ' % (name, inst, name)
    if name in GLOBAL:
        body = 'auto f = (PFN_%s)vk_icdGetInstanceProcAddr(VK_NULL_HANDLE, "%s"); ' % (name, name)
    if name == 'vkCreateInstance':
        body += 'VkResult r = f(%s); if (r == VK_SUCCESS) g_instance = *pInstance; return r;' % ', '.join(names)
    elif ret.strip() == 'void':
        body += call + ';'
    else:
        body += 'return ' + call + ';'
    out.append('extern "C" VKAPI_ATTR %s VKAPI_CALL %s(%s) { %s }' % (ret.strip(), name, params, body))
out.append('extern "C" VKAPI_ATTR PFN_vkVoidFunction VKAPI_CALL vkGetInstanceProcAddr(VkInstance i, const char* n) '
           '{ return vk_icdGetInstanceProcAddr(i, n); }')
print('\n'.join(out))
