"""Give sce_module/libc.prx the exports a title's loader expects (see libc-exports.tsv).

The system loader starts libSceLibcInternal, which loads /app0/sce_module/libc.prx and
looks symbols up in its "libc" and "libc_setjmp" libraries. ps5-native-tool cannot publish
exports yet, so this does it after conversion:

  gen <tsv> <out.S>                       assembly: one label per export (sf3_e<i>)
  publish <tsv> <in.so> <in.elf> <out>    add the labels to the converted module's dynsym
  check <tsv> <elf>                       fail unless the module exports exactly the table

A few exports have real MIT implementations here (setjmp family, atexit family, the
malloc-init hook, Need_sceLibc). Every other function is a trap: "mov $i,%eax; ud2", so a
crash names the export (rax = row index) that something actually called.
"""
import hashlib, struct, sys, base64

SUF = bytes.fromhex("518d64a635ded8c1e6b039b1c3e55230")
def nid(n):
    return base64.b64encode(hashlib.sha1(n.encode() + SUF).digest()[:8]).decode().replace("/", "-")[:11]
B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+-"
def enc(i):  # NID suffix letters: base64 digits, most significant first
    s = ""
    while True:
        s = B64[i & 63] + s; i >>= 6
        if not i: return s

def table(p):
    rows = []
    for l in open(p):
        if l.startswith("#") or not l.strip(): continue
        n, lib, bind, kind, size = l.split("\t"); rows.append((n, lib, bind, kind, int(size)))
    return rows

SETJMP = """\tmovq (%rsp),%rdx\n\tmovq %rbx,0(%rdi)\n\tmovq %rbp,8(%rdi)\n\tmovq %r12,16(%rdi)
\tmovq %r13,24(%rdi)\n\tmovq %r14,32(%rdi)\n\tmovq %r15,40(%rdi)\n\tleaq 8(%rsp),%rcx
\tmovq %rcx,48(%rdi)\n\tmovq %rdx,56(%rdi)\n\tstmxcsr 64(%rdi)\n\tfnstcw 68(%rdi)\n\txorl %eax,%eax\n\tret\n"""
LONGJMP = """\tmovl %esi,%eax\n\ttestl %eax,%eax\n\tjnz 1f\n\tincl %eax\n1:\tmovq 0(%rdi),%rbx
\tmovq 8(%rdi),%rbp\n\tmovq 16(%rdi),%r12\n\tmovq 24(%rdi),%r13\n\tmovq 32(%rdi),%r14
\tmovq 40(%rdi),%r15\n\tldmxcsr 64(%rdi)\n\tfldcw 68(%rdi)\n\tmovq 48(%rdi),%rsp\n\tjmpq *56(%rdi)\n"""
REAL = {nid("setjmp"): SETJMP, nid("_setjmp"): SETJMP, nid("longjmp"): LONGJMP, nid("_longjmp"): LONGJMP,
        nid("atexit"): "\txorl %eax,%eax\n\tret\n", nid("__cxa_atexit"): "\txorl %eax,%eax\n\tret\n",
        nid("__cxa_finalize"): "\tret\n", nid("_malloc_init"): "\txorl %eax,%eax\n\tret\n"}
OBJ_INIT = {nid("Need_sceLibc"): "\t.long 1\n"}

def gen(rows, out):
    t, d, tl = [], [], []
    for i, (n, lib, bind, kind, size) in enumerate(rows):
        lab = f"sf3_e{i}"
        if kind == "func":
            t.append(f"\t.p2align 3\n\t.type {lab},@function\n{lab}:\n" + REAL.get(n, f"\tmovl ${i},%eax\n\tud2\n"))
        else:
            body = OBJ_INIT.get(n, f"\t.zero {max(size, 1)}\n")
            (tl if kind == "tls" else d).append(f"\t.p2align 4\n\t.type {lab},@{'tls_object' if kind == 'tls' else 'object'}\n{lab}:\n{body}\t.size {lab},{size}\n")
    open(out, "w").write("# generated by companion-exports.py gen; MIT\n\t.text\n" + "".join(t) +
                         "\t.data\n" + "".join(d) + '\t.section .tbss,"awT",@nobits\n' + "".join(tl))

def phdrs(d):
    off, n = struct.unpack_from("<Q", d, 32)[0], struct.unpack_from("<H", d, 56)[0]
    return [(off + i * 56,) + struct.unpack_from("<IIQQQQQQ", d, off + i * 56) for i in range(n)]

def so_symbols(d):  # name -> value from the linker output's .symtab
    shoff, shnum = struct.unpack_from("<Q", d, 40)[0], struct.unpack_from("<H", d, 60)[0]
    sh = [struct.unpack_from("<IIQQQQIIQQ", d, shoff + i * 64) for i in range(shnum)]
    out = {}
    for s in sh:
        if s[1] != 2: continue
        st = sh[s[6]]
        for j in range(s[5] // 24):
            nm, info, oth, shn, val, sz = struct.unpack_from("<IBBHQQ", d, s[4] + j * 24)
            name = d[st[4] + nm:d.index(b"\0", st[4] + nm)].decode()
            if name.startswith("sf3_e"): out[name] = val
    return out

def dynlib(d):
    ph = phdrs(d)
    seg = next(p for p in ph if p[1] == 1 and p[2] == 0)
    dyn = next(p for p in ph if p[1] == 2)
    ents = [struct.unpack_from("<QQ", d, dyn[3] + j * 16) for j in range(dyn[6] // 16)]
    return ph, seg, dyn, ents

def elf_hash(s):
    h = 0
    for c in s:
        h = ((h << 4) + c) & 0xFFFFFFFF; g = h & 0xF0000000
        if g: h ^= g >> 24
        h &= ~g & 0xFFFFFFFF
    return h

def publish(rows, so, elf, out):
    d = bytearray(open(elf, "rb").read()); syms = so_symbols(open(so, "rb").read())
    ph, seg, dyn, ents = dynlib(d)
    fo = lambda va: va - seg[4] + seg[3]
    get = lambda t: next(v for k, v in ents if k == t)
    strtab = bytearray(d[fo(get(5)):fo(get(5)) + get(0xA)])
    symtab = bytearray(d[fo(get(6)):fo(get(6)) + get(0x6100003F)])
    libc = next(v for k, v in ents if k == 0x61000047)
    ids = {"libc": libc >> 48, "libc_setjmp": (libc >> 48) + 1}
    sj_name = len(strtab); strtab += b"libc_setjmp\0"
    kinds = {"func": 2, "object": 1, "tls": 6}; shn = {"func": 3, "object": 6, "tls": 17}
    for i, (n, lib, bind, kind, size) in enumerate(rows):
        off = len(strtab); strtab += f"{n}#{enc(ids[lib])}#A\0".encode()
        info = ((2 if bind == "weak" else 1) << 4) | kinds[kind]
        symtab += struct.pack("<IBBHQQ", off, info, 0, shn[kind], syms[f"sf3_e{i}"], size)
    nsym = len(symtab) // 24; nb = max(1, nsym // 2) | 1; bucket = [0] * nb; chain = [0] * nsym
    for j in range(nsym):
        nm = struct.unpack_from("<I", symtab, j * 24)[0]
        h = elf_hash(strtab[nm:strtab.index(b"\0", nm)]) % nb; chain[j] = bucket[h]; bucket[h] = j
    hashtab = struct.pack(f"<II{nb}I{nsym}I", nb, nsym, *bucket, *chain)
    end_va = seg[4] + seg[6]; blob = bytearray(); place = {}
    for name, b in (("str", strtab), ("sym", symtab), ("hash", hashtab)):
        blob += b"\0" * (-len(blob) % 8); place[name] = end_va + len(blob); blob += b
    blob += b"\0" * (-len(blob) % 16); grow = len(blob); cut = seg[3] + seg[6]
    new = {5: place["str"], 0xA: len(strtab), 6: place["sym"], 0x6100003F: len(symtab), 4: place["hash"], 0x6100003D: len(hashtab)}
    ents = [(k, new.get(k, v)) for k, v in ents]
    free = [j for j, (k, v) in enumerate(ents) if k == 0 and v == 0][:-1]
    ents[free[0]] = (0x61000047, (ids["libc_setjmp"] << 48) | (1 << 32) | sj_name)
    ents[free[1]] = (0x61000017, (ids["libc_setjmp"] << 48) | 1)
    for j, (k, v) in enumerate(ents): struct.pack_into("<QQ", d, dyn[3] + j * 16, k, v)
    for p in ph:  # grow the dynlib segment, move what follows it in the file
        if p[1] == 7 and p[6] > p[7]:  # converter underflows filesz for a .tbss-only TLS
            struct.pack_into("<Q", d, p[0] + 32, 0)
        if p == seg: struct.pack_into("<QQ", d, p[0] + 32, seg[6] + grow, seg[7] + grow)
        elif p[3] >= cut: struct.pack_into("<Q", d, p[0] + 8, p[3] + grow)
    if struct.unpack_from("<Q", d, 40)[0]: raise SystemExit("unexpected section headers")
    open(out, "wb").write(bytes(d[:cut] + blob + d[cut:]))

def check(rows, elf):
    d = open(elf, "rb").read(); ph, seg, dyn, ents = dynlib(d)
    fo = lambda va: va - seg[4] + seg[3]; get = lambda t: next(v for k, v in ents if k == t)
    st, sy = fo(get(5)), fo(get(6)); strs = lambda o: d[st + o:d.index(b"\0", st + o)].decode()
    libs = {v >> 48: strs(v & 0xFFFFFFFF) for k, v in ents if k == 0x61000047}
    have = set()
    for j in range(get(0x6100003F) // 24):
        nm, info, oth, shn, val, sz = struct.unpack_from("<IBBHQQ", d, sy + j * 24)
        if not shn: continue
        n, l, m = strs(nm).split("#"); li = 0
        for c in l: li = li * 64 + B64.index(c)
        have.add((n, libs[li], "weak" if info >> 4 == 2 else "global", {1: "object", 2: "func", 6: "tls"}[info & 15], sz))
    want = set(rows)
    if have != want:
        print(f"export mismatch: {len(want - have)} missing, {len(have - want)} extra", file=sys.stderr)
        for r in sorted(want - have)[:10]: print(" missing", r, file=sys.stderr)
        for r in sorted(have - want)[:10]: print(" extra", r, file=sys.stderr)
        raise SystemExit(1)
    print(f"exports match: {len(have)} NIDs in {sorted(set(libs.values()))}")

if __name__ == "__main__":
    a = sys.argv; rows = table(a[2])
    {"gen": lambda: gen(rows, a[3]), "publish": lambda: publish(rows, a[3], a[4], a[5]), "check": lambda: check(rows, a[3])}[a[1]]()
