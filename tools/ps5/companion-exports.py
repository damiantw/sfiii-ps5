"""Give sce_module/libc.prx the exports a title's loader expects (see libc-exports.tsv).

The system loader starts libSceLibcInternal, which loads /app0/sce_module/libc.prx and
looks symbols up in its "libc" and "libc_setjmp" libraries. ps5-native-tool cannot publish
exports yet, so this does it after conversion:

  gen <tsv> <out.S>                       assembly: one label per export (sf3_e<i>)
  publish <tsv> <in.so> <in.elf> <out>    add the labels to the converted module's dynsym
  check <tsv> <elf>                       fail unless the module exports exactly the table

A few exports have real MIT implementations here (setjmp family, atexit family, the
malloc-init hook, Need_sceLibc). Every other function records its table row in
sf3_last_row (and counts calls in sf3_calls) and returns 0, so nothing traps while the
system initialises the module.

publish rebuilds the whole dynlib data segment in the layout system modules use (strtab,
symtab, relocations, hash, note, dynamic; SONAME, module info and export libraries before
the relocation tags; DT_INIT/DT_FINI present; one hash bucket per symbol). The module's
thread-local exports live in .tdata inside the RELRO segment, as in system modules.

Variants (SF3_COMPANION_EXPORTS): full, notls (drop the four TLS exports), none (publish
nothing; only the layout rebuild).
"""
import hashlib, struct, sys, base64

SUF = bytes.fromhex("518d64a635ded8c1e6b039b1c3e55230")
def nid(n):
    return base64.b64encode(hashlib.sha1(n.encode() + SUF).digest()[7::-1]).decode().replace("/", "-")[:11]
B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+-"
def enc(i):  # NID suffix letters: base64 digits, most significant first
    s = ""
    while True:
        s = B64[i & 63] + s; i >>= 6
        if not i: return s

def table(p):
    rows = []
    for l in open(p):
        if l.startswith("#") or not l.strip(): continue
        n, lib, bind, kind, size = l.split("\t"); rows.append((n, lib, bind, kind, int(size)))
    return rows

SETJMP = """\tmovq (%rsp),%rdx\n\tmovq %rbx,0(%rdi)\n\tmovq %rbp,8(%rdi)\n\tmovq %r12,16(%rdi)
\tmovq %r13,24(%rdi)\n\tmovq %r14,32(%rdi)\n\tmovq %r15,40(%rdi)\n\tleaq 8(%rsp),%rcx
\tmovq %rcx,48(%rdi)\n\tmovq %rdx,56(%rdi)\n\tstmxcsr 64(%rdi)\n\tfnstcw 68(%rdi)\n\txorl %eax,%eax\n\tret\n"""
LONGJMP = """\tmovl %esi,%eax\n\ttestl %eax,%eax\n\tjnz 1f\n\tincl %eax\n1:\tmovq 0(%rdi),%rbx
\tmovq 8(%rdi),%rbp\n\tmovq 16(%rdi),%r12\n\tmovq 24(%rdi),%r13\n\tmovq 32(%rdi),%r14
\tmovq 40(%rdi),%r15\n\tldmxcsr 64(%rdi)\n\tfldcw 68(%rdi)\n\tmovq 48(%rdi),%rsp\n\tjmpq *56(%rdi)\n"""
REAL = {nid("setjmp"): SETJMP, nid("_setjmp"): SETJMP, nid("longjmp"): LONGJMP, nid("_longjmp"): LONGJMP,
        nid("atexit"): "\txorl %eax,%eax\n\tret\n", nid("__cxa_atexit"): "\txorl %eax,%eax\n\tret\n",
        nid("__cxa_finalize"): "\tret\n", nid("_malloc_init"): "\txorl %eax,%eax\n\tret\n"}
OBJ_INIT = {nid("Need_sceLibc"): "\t.long 1\n"}

def variant(rows, v):
    if v == "none": return []
    if v == "notls": return [r for r in rows if r[3] != "tls"]
    return rows

PROTECTED = {nid("Need_sceLibc")}
assert nid("Need_sceLibc") == "P330P3dFF68"  # the published NID hash

def gen(rows, out):
    t = ["\t.p2align 4\nsf3_stub:\n\tmovl %eax,sf3_last_row(%rip)\n\tlock incl sf3_calls(%rip)\n\txorl %eax,%eax\n\tret\n",
         "\t.p2align 3\n\t.type sf3_init,@function\nsf3_init:\n\txorl %eax,%eax\n\tret\n"]
    d = ["\t.p2align 2\nsf3_last_row:\n\t.long -1\nsf3_calls:\n\t.long 0\n"]; tl = []
    for i, (n, lib, bind, kind, size) in rows:
        lab = f"sf3_e{i}"
        if kind == "func":
            t.append(f"\t.p2align 3\n\t.type {lab},@function\n{lab}:\n" + REAL.get(n, f"\tmovl ${i},%eax\n\tjmp sf3_stub\n"))
        else:
            body = OBJ_INIT.get(n, f"\t.zero {max(size, 1)}\n")
            (tl if kind == "tls" else d).append(f"\t.p2align 4\n\t.type {lab},@{'tls_object' if kind == 'tls' else 'object'}\n{lab}:\n{body}\t.size {lab},{size}\n")
    open(out, "w").write("# generated by companion-exports.py gen; MIT\n\t.text\n" + "".join(t) +
                         "\t.data\n" + "".join(d) + '\t.section .tdata,"awT",@progbits\n' + "".join(tl))

def phdrs(d):
    off, n = struct.unpack_from("<Q", d, 32)[0], struct.unpack_from("<H", d, 56)[0]
    return [(off + i * 56,) + struct.unpack_from("<IIQQQQQQ", d, off + i * 56) for i in range(n)]

def so_symbols(d):  # name -> value from the linker output's .symtab
    shoff, shnum = struct.unpack_from("<Q", d, 40)[0], struct.unpack_from("<H", d, 60)[0]
    sh = [struct.unpack_from("<IIQQQQIIQQ", d, shoff + i * 64) for i in range(shnum)]
    out = {}
    for s in sh:
        if s[1] != 2: continue
        st = sh[s[6]]
        for j in range(s[5] // 24):
            nm, info, oth, shn, val, sz = struct.unpack_from("<IBBHQQ", d, s[4] + j * 24)
            name = d[st[4] + nm:d.index(b"\0", st[4] + nm)].decode()
            if name.startswith("sf3_"): out[name] = val
    return out

def dynlib(d):
    ph = phdrs(d)
    seg = next(p for p in ph if p[1] == 1 and p[2] == 0)
    dyn = next(p for p in ph if p[1] == 2)
    ents = [struct.unpack_from("<QQ", d, dyn[3] + j * 16) for j in range(dyn[6] // 16)]
    return ph, seg, dyn, ents

def elf_hash(s):
    h = 0
    for c in s:
        h = ((h << 4) + c) & 0xFFFFFFFF; g = h & 0xF0000000
        if g: h ^= g >> 24
        h &= ~g & 0xFFFFFFFF
    return h

def publish(rows, so, elf, out):
    d = bytearray(open(elf, "rb").read()); syms = so_symbols(open(so, "rb").read())
    ph, seg, dyn, ents = dynlib(d)
    fo = lambda va: va - seg[4] + seg[3]
    get = lambda t: next(v for k, v in ents if k == t)
    blk = lambda va, n: bytes(d[fo(va):fo(va) + n])
    strtab = bytearray(blk(get(5), get(0xA))); symtab = bytearray(blk(get(6), get(0x6100003F)))
    rela = blk(get(7), get(8)); jmprel = blk(get(0x17), get(2)) if get(2) else b""
    note = next(p for p in ph if p[1] == 4 and seg[3] <= p[3] < seg[3] + seg[6])
    notes = bytes(d[note[3]:note[3] + note[6]])
    libc = next(v for k, v in ents if k == 0x61000047)
    ids = {"libc": libc >> 48, "libc_setjmp": (libc >> 48) + 1}
    extra = []
    if any(r[1] == "libc_setjmp" for i, r in rows):
        sj = len(strtab); strtab += b"libc_setjmp\0"
        extra = [(0x61000047, (ids["libc_setjmp"] << 48) | (1 << 32) | sj), (0x61000017, (ids["libc_setjmp"] << 48) | 1)]
    kinds = {"func": 2, "object": 1, "tls": 6}; shn = {"func": 3, "object": 6, "tls": 17}
    for i, (n, lib, bind, kind, size) in rows:
        off = len(strtab); strtab += f"{n}#{enc(ids[lib])}#A\0".encode()
        info = ((2 if bind == "weak" else 1) << 4) | kinds[kind]
        symtab += struct.pack("<IBBHQQ", off, info, 3 if n in PROTECTED else 0, shn[kind], syms[f"sf3_e{i}"], size)
    nsym = len(symtab) // 24; nb = nsym; bucket = [0] * nb; chain = [0] * nsym
    for j in range(nsym):
        nm = struct.unpack_from("<I", symtab, j * 24)[0]
        h = elf_hash(strtab[nm:strtab.index(b"\0", nm)]) % nb; chain[j] = bucket[h]; bucket[h] = j
    hashtab = struct.pack(f"<II{nb}I{nsym}I", nb, nsym, *bucket, *chain)
    # layout: strtab, symtab, jmprel, rela, hash, note, dynamic (as in system modules)
    base = seg[4]; blob = bytearray(); at = {}
    def put(name, b, al):
        blob.extend(b"\0" * (-len(blob) % al)); at[name] = base + len(blob); blob.extend(b)
    put("str", strtab, 8); put("sym", symtab, 8)
    if jmprel: put("jmprel", jmprel, 8)
    put("rela", rela, 8); put("hash", hashtab, 8); put("note", notes, 4)
    # dynamic, in the system module order
    keep = lambda t: [(k, v) for k, v in ents if k == t]
    imports = []
    for j, (k, v) in enumerate(ents):  # NEEDED / module / library triples, in order
        if k == 0x61000045:  # needed module version x.0 -> 1.1, as the system modules record it
            v |= 0x0101 << 32
        if k in (1, 0x61000045, 0x61000049, 0x61000019): imports.append((k, v))
    new = (imports + keep(0xE) + keep(0x61000043) + keep(0x61000011) + keep(0x61000041) +
           keep(0x61000047)[:1] + keep(0x61000017)[:1] + extra +
           [(7, at["rela"]), (8, len(rela)), (9, 24), (0x6FFFFFF9, get(0x6FFFFFF9)),
            (0x17, at.get("jmprel", at["rela"])), (2, len(jmprel)), (3, get(3)), (0x14, 7),
            (6, at["sym"]), (0xB, 24), (5, at["str"]), (0xA, len(strtab)), (4, at["hash"]),
            (0x19, 0), (0x1B, 0), (0x1A, 0), (0x1C, 0),
            (0xC, syms.get("sf3_companion_init", syms["sf3_init"])), (0xD, syms["sf3_init"]),
            (0x6100003F, len(symtab)), (0x6100003D, len(hashtab))])
    new += [(0, 0)] * 8
    put("dyn", b"".join(struct.pack("<QQ", k, v) for k, v in new), 8)
    blob.extend(b"\0" * (-(len(blob) - seg[6]) % 16))  # keep later offsets 16-aligned
    old_end = seg[3] + seg[6]; grow = len(blob) - seg[6]
    if grow % 16: raise SystemExit("unaligned growth")
    for p in ph:
        # the converter starts the segment holding .tdata after it (unaligned); system modules
        # keep TLS inside a page-aligned RW segment, as the linker laid it out
        if p[1] in (1, 0x6474E552) and p[2] & 6 and p[4] % 0x4000:
            k = p[4] % 0x4000
            struct.pack_into("<QQQQQ", d, p[0] + 8, p[3] - k, p[4] - k, p[5] - k, p[6] + k, p[7] + (0 if p[1] != 1 else k))
        if p[1] == 7: struct.pack_into("<Q", d, p[0] + 48, 0x10)
        if p == seg: struct.pack_into("<QQ", d, p[0] + 32, len(blob), len(blob))
        elif p == note: struct.pack_into("<QQQ", d, p[0] + 8, seg[3] + at["note"] - base, at["note"], at["note"])
        elif p == dyn:
            struct.pack_into("<QQQ", d, p[0] + 8, seg[3] + at["dyn"] - base, at["dyn"], at["dyn"])
            struct.pack_into("<QQ", d, p[0] + 32, len(new) * 16, len(new) * 16)
        elif p[3] >= old_end: struct.pack_into("<Q", d, p[0] + 8, p[3] + grow)
        if p[1] == 7 and p[6] > p[7]: raise SystemExit("TLS segment with bad filesz; expected .tdata")
    if struct.unpack_from("<Q", d, 40)[0]: raise SystemExit("unexpected section headers")
    d = bytearray(d[:seg[3]] + blob + d[old_end:])
    # The converter writes the version segment (0x6FFFFF01) in application form: "app_crt.o:" and
    # one entry per dependency. A module's holds a single entry naming the module itself.
    for p in phdrs(d):
        if p[1] != 0x6FFFFF01: continue
        old = bytes(d[p[3]:p[3] + p[6]]); words = old[old.index(b":") + 1:old.index(b":") + 17]
        name = strtab[get(0x61000043) & 0xFFFFFFFF:strtab.index(b"\0", get(0x61000043) & 0xFFFFFFFF)]
        body = b"\x08" + name + b":" + words
        new = struct.pack("<HH", 0, len(body)) + body
        d[p[3]:p[3] + p[6]] = new + b"\0" * (p[6] - len(new))
        struct.pack_into("<QQQ", d, p[0] + 32, len(new), (len(new) + 15) & ~15, 0x10)
    open(out, "wb").write(bytes(d))

def check(rows, elf):
    d = open(elf, "rb").read(); ph, seg, dyn, ents = dynlib(d)
    fo = lambda va: va - seg[4] + seg[3]; get = lambda t: next(v for k, v in ents if k == t)
    st, sy = fo(get(5)), fo(get(6)); strs = lambda o: d[st + o:d.index(b"\0", st + o)].decode()
    libs = {v >> 48: strs(v & 0xFFFFFFFF) for k, v in ents if k == 0x61000047}
    have = set()
    for j in range(get(0x6100003F) // 24):
        nm, info, oth, shn, val, sz = struct.unpack_from("<IBBHQQ", d, sy + j * 24)
        if not shn: continue
        n, l, m = strs(nm).split("#"); li = 0
        for c in l: li = li * 64 + B64.index(c)
        have.add((n, libs[li], "weak" if info >> 4 == 2 else "global", {1: "object", 2: "func", 6: "tls"}[info & 15], sz))
    want = set(r for i, r in rows)
    if have != want:
        print(f"export mismatch: {len(want - have)} missing, {len(have - want)} extra", file=sys.stderr)
        for r in sorted(want - have)[:10]: print(" missing", r, file=sys.stderr)
        for r in sorted(have - want)[:10]: print(" extra", r, file=sys.stderr)
        raise SystemExit(1)
    print(f"exports match: {len(have)} NIDs in {sorted(set(libs.values()))}")

if __name__ == "__main__":
    import os
    a = sys.argv; allrows = table(a[2]); v = os.environ.get("SF3_COMPANION_EXPORTS", "full")
    rows = [(i, r) for i, r in enumerate(allrows) if r in variant(allrows, v)]
    {"gen": lambda: gen(rows, a[3]), "publish": lambda: publish(rows, a[3], a[4], a[5]), "check": lambda: check(rows, a[3])}[a[1]]()
